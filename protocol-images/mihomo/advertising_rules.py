def ad_catalog_matchers():
    return [(parts[0], parts[1]) for rule in AD_RULES
            if (parts := rule.split(","))[0] in {"DOMAIN", "DOMAIN-SUFFIX"}]


def mihomo_ad_base_rule(provider):
    clauses = ",".join(f"({kind},{domain})" for kind, domain in ad_catalog_matchers())
    return f"AND,((RULE-SET,{provider}),(NOT,((OR,({clauses}))))),REJECT"
